package ca.truenorthtak.gateway.bench;

import ca.truenorthtak.gateway.Gateway;
import ca.truenorthtak.gateway.codec.Codec;
import ca.truenorthtak.gateway.codec.ExchangeXmlCodec;
import ca.truenorthtak.gateway.codec.XsdGenerator;
import ca.truenorthtak.gateway.fec.Fragmenter;
import ca.truenorthtak.gateway.fec.RedundancyPolicy;
import ca.truenorthtak.gateway.link.LinkProfile;
import ca.truenorthtak.gateway.link.LossModel;
import ca.truenorthtak.gateway.model.Message;
import ca.truenorthtak.gateway.samples.Samples;

import javax.xml.XMLConstants;
import javax.xml.transform.stream.StreamSource;
import javax.xml.validation.Schema;
import javax.xml.validation.SchemaFactory;
import java.io.ByteArrayInputStream;
import java.io.IOException;
import java.io.StringReader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.Arrays;
import java.util.List;
import java.util.Locale;
import java.util.Random;

/**
 * Reproducible evidence run. Writes results/BENCHMARK.md, example messages in
 * every format and the generated XML schema. All randomness is seeded.
 *
 * Usage: Bench [outputDir] [trials]
 */
public final class Bench {
    private static final long SEED = 20261010L;

    public static void main(String[] args) throws Exception {
        Path root = Paths.get(args.length > 0 ? args[0] : ".");
        int trials = args.length > 1 ? Integer.parseInt(args[1]) : 10000;
        Gateway gw = Gateway.withDefaults();
        List<Message> samples = Arrays.asList(Samples.medevac(gw.definitions), Samples.spotrep(gw.definitions));

        StringBuilder md = new StringBuilder();
        md.append("# Benchmark results\n\n");
        md.append("Generated by `bench` (`gradle :bench:run`). Synthetic, unclassified messages; ")
          .append("representative link profiles from `docs/LINK_PROFILES.md`. Seed ").append(SEED)
          .append(", ").append(trials).append(" trials per loss scenario. Java ")
          .append(System.getProperty("java.version")).append(".\n\n");

        writeExamples(gw, samples, root.resolve("examples"));
        md.append(schemaSection(gw, samples, root.resolve("schema")));
        md.append(sizeSection(gw, samples));
        md.append(lossSection(gw, trials));
        md.append(timingSection(gw, samples));

        Path out = root.resolve("results");
        Files.createDirectories(out);
        Files.write(out.resolve("BENCHMARK.md"), md.toString().getBytes(StandardCharsets.UTF_8));
        System.out.print(md);
    }

    private static String sizeSection(Gateway gw, List<Message> samples) {
        StringBuilder b = new StringBuilder("## 1. Message size and airtime by format\n\n");
        b.append("Airtime = bytes x 8 / link rate, before fragment headers, FEC and modem framing.\n\n");
        b.append("| Message | Format | Bytes | vs CoT | VLF 50 bps | HF 2400 bps | SATCOM 9600 bps | MANET 1 Mbps |\n");
        b.append("|---|---|---:|---:|---:|---:|---:|---:|\n");
        for (Message m : samples) {
            int cot = gw.encode(m, "cot").length;
            for (Codec c : gw.codecs.all()) {
                int n = c.encode(m).length;
                b.append("| ").append(m.def.id).append(" | ").append(c.name()).append(" | ").append(n)
                 .append(" | ").append(pct(n, cot));
                for (LinkProfile l : LinkProfile.all()) b.append(" | ").append(secs(l.airtimeSeconds(n)));
                b.append(" |\n");
            }
        }
        b.append('\n');
        return b.toString();
    }

    private static String lossSection(Gateway gw, int trials) {
        StringBuilder b = new StringBuilder("## 2. Delivery over lossy one-way links (no retransmission)\n\n");
        b.append("Each trial encodes the MEDEVAC request (precedence IMMEDIATE), fragments it for the link, ")
         .append("drops fragments according to the loss model, then attempts real reassembly and decoding. ")
         .append("A trial succeeds only if the decoded message equals the original. ")
         .append("\"No FEC\" needs every fragment; \"RS FEC\" uses the standard precedence policy ")
         .append("(IMMEDIATE = 100% parity) and needs any k of n fragments.\n\n");
        b.append("| Link | Format | Loss model | Fragments (no FEC / RS) | Airtime (no FEC / RS) | Delivered, no FEC | Delivered, RS FEC |\n");
        b.append("|---|---|---|---:|---:|---:|---:|\n");
        Message m = Samples.medevac(gw.definitions);
        List<LossModel> models = Arrays.asList(
                LossModel.random(0.10), LossModel.random(0.20), LossModel.random(0.30), LossModel.random(0.40),
                LossModel.burst(0.10, 0.30, 0.80));
        Object[][] cases = {
                {LinkProfile.VLF_BROADCAST, "bin"},
                {LinkProfile.HF_DATA, "bin"},
                {LinkProfile.HF_DATA, "slash"},
        };
        for (Object[] c : cases) {
            LinkProfile link = (LinkProfile) c[0];
            String fmt = (String) c[1];
            byte[] payload = gw.encode(m, fmt);
            List<byte[]> plain = Fragmenter.split(payload, m.serial(), link.maxFragmentBytes, m.precedence(), RedundancyPolicy.none());
            List<byte[]> coded = Fragmenter.split(payload, m.serial(), link.maxFragmentBytes, m.precedence(), RedundancyPolicy.standard());
            for (LossModel lm : models) {
                double a = deliver(gw, m, fmt, plain, lm, trials, new Random(SEED));
                double r = deliver(gw, m, fmt, coded, lm, trials, new Random(SEED));
                b.append("| ").append(link.name).append(" | ").append(fmt).append(" | ").append(lm.describe())
                 .append(" | ").append(plain.size()).append(" / ").append(coded.size())
                 .append(" | ").append(secs(link.airtimeSeconds(bytes(plain)))).append(" / ").append(secs(link.airtimeSeconds(bytes(coded))))
                 .append(" | ").append(String.format(Locale.ROOT, "%.1f%%", a * 100))
                 .append(" | **").append(String.format(Locale.ROOT, "%.1f%%", r * 100)).append("** |\n");
            }
        }
        b.append('\n');
        return b.toString();
    }

    private static double deliver(Gateway gw, Message expected, String fmt, List<byte[]> frags, LossModel lm,
                                  int trials, Random rng) {
        int ok = 0;
        for (int t = 0; t < trials; t++) {
            lm.reset(rng);
            Fragmenter.Reassembler r = new Fragmenter.Reassembler();
            byte[] payload = null;
            for (byte[] f : frags) {
                if (lm.lost(rng)) continue;
                byte[] res = r.accept(f);
                if (res != null) payload = res;
            }
            if (payload != null && expected.equals(gw.decode(payload, fmt))) ok++;
        }
        return ok / (double) trials;
    }

    private static String timingSection(Gateway gw, List<Message> samples) {
        StringBuilder b = new StringBuilder("## 3. Processing cost (encode + decode)\n\n");
        b.append("Median of 2,000 runs after warm-up on the benchmark host (a desktop JVM; Android handsets will be slower). ")
         .append("Shows the work is cheap enough for a phone.\n\n");
        b.append("| Message | Format | Median microseconds |\n|---|---|---:|\n");
        for (Message m : samples) {
            for (Codec c : gw.codecs.all()) {
                for (int w = 0; w < 2000; w++) c.decode(c.encode(m));
                long[] t = new long[2000];
                for (int k = 0; k < t.length; k++) {
                    long s = System.nanoTime();
                    c.decode(c.encode(m));
                    t[k] = System.nanoTime() - s;
                }
                Arrays.sort(t);
                b.append("| ").append(m.def.id).append(" | ").append(c.id()).append(" | ")
                 .append(String.format(Locale.ROOT, "%.0f", t[t.length / 2] / 1000.0)).append(" |\n");
            }
        }
        b.append('\n');
        return b.toString();
    }

    private static String schemaSection(Gateway gw, List<Message> samples, Path dir) throws Exception {
        Files.createDirectories(dir);
        String xsd = XsdGenerator.generate(gw.definitions.all());
        Files.write(dir.resolve("gateway-exchange-1.xsd"), xsd.getBytes(StandardCharsets.UTF_8));
        Schema s = SchemaFactory.newInstance(XMLConstants.W3C_XML_SCHEMA_NS_URI).newSchema(new StreamSource(new StringReader(xsd)));
        StringBuilder b = new StringBuilder("## 0. Schema validation\n\n");
        b.append("`schema/gateway-exchange-1.xsd` is generated from the message definitions. ")
         .append("Each sample's XML exchange output is validated against it with the JDK's W3C XML Schema validator:\n\n");
        for (Message m : samples) {
            s.newValidator().validate(new StreamSource(new ByteArrayInputStream(gw.encode(m, "xml"))));
            b.append("- ").append(m.def.id).append(": **valid**\n");
        }
        b.append('\n');
        return b.toString();
    }

    private static void writeExamples(Gateway gw, List<Message> samples, Path dir) throws IOException {
        Files.createDirectories(dir);
        ExchangeXmlCodec pretty = new ExchangeXmlCodec(gw.definitions, true);
        for (Message m : samples) {
            String base = m.def.id.toLowerCase(Locale.ROOT);
            Files.write(dir.resolve(base + ".cot.xml"), gw.encode(m, "cot"));
            Files.write(dir.resolve(base + ".exchange.xml"), pretty.encode(m));
            Files.write(dir.resolve(base + ".slash.txt"), gw.encode(m, "slash"));
            byte[] bin = gw.encode(m, "bin");
            Files.write(dir.resolve(base + ".bin"), bin);
            Files.write(dir.resolve(base + ".bin.hex.txt"), hex(bin).getBytes(StandardCharsets.US_ASCII));
        }
    }

    private static String hex(byte[] b) {
        StringBuilder s = new StringBuilder();
        for (int i = 0; i < b.length; i++) {
            s.append(String.format("%02X", b[i] & 0xFF)).append(i % 16 == 15 ? '\n' : ' ');
        }
        return s.toString().trim() + "\n";
    }

    private static int bytes(List<byte[]> frags) {
        int n = 0;
        for (byte[] f : frags) n += f.length;
        return n;
    }

    private static String pct(int n, int base) {
        if (n == base) return "-";
        double d = (n / (double) base - 1) * 100;
        return String.format(Locale.ROOT, "%+.0f%%", d);
    }

    private static String secs(double s) {
        if (s < 1) return String.format(Locale.ROOT, "%.1f ms", s * 1000);
        if (s < 60) return String.format(Locale.ROOT, "%.1f s", s);
        return String.format(Locale.ROOT, "%.1f min", s / 60);
    }

}
